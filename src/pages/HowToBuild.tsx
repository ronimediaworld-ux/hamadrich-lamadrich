function guideToText(g: Guide): string {
  const L: string[] = [g.heading, '', g.intro, '', g.partsTitle + ':'];
  g.parts.forEach((p) => L.push(`• ${p.name} (${p.meta}) — ${p.what}  [טיפ: ${p.tip}]`));
  L.push('', 'שלב אחרי שלב:');
  g.steps.forEach((s) => L.push(`${s.n}. ${s.title} — ${s.body}`));
  L.push('', 'טעויות נפוצות:');
  g.mistakes.forEach((m) => L.push(`- ${m}`));
  L.push('', 'רשימת בדיקה:');
  g.checklist.forEach((c) => L.push(`☐ ${c}`));
  return L.join('\n').trim();
}

