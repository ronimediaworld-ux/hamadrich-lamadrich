export function HowToBuild() {
  useDocumentTitle('נדבר ת׳כלס');
  const [searchParams] = useSearchParams();
  const wanted = searchParams.get('guide');
  const [active, setActive] = useState(GUIDES.some((g) => g.id === wanted) ? (wanted as string) : GUIDES[0].id);
  useEffect(() => {
    if (wanted && GUIDES.some((g) => g.id === wanted)) setActive(wanted);
  }, [wanted]);
  const guide = GUIDES.find((g) => g.id === active) ?? GUIDES[0];
  const contentRef = useRef<HTMLDivElement>(null);
  // לחיצה על לשונית: עוברים מיד לתוכן שלה (בטלפון הלשוניות תופסות כמה שורות והתוכן מתחתן)
  function openGuide(id: string) {
    setActive(id);
    window.requestAnimationFrame(() => contentRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' }));
  }

  return (
    <div className="wrap" style={{ paddingTop: 30, paddingBottom: 70, maxWidth: 760 }}>
      <Reveal>
        <div style={{ display: 'flex', alignItems: 'center', gap: 14, marginBottom: 16 }}>
          <MascotIcon size={48} />
          <div>
            <h1 style={{ fontSize: 28, fontWeight: 800 }}>נדבר ת׳כלס</h1>
            <p style={{ fontSize: 13.5, color: 'var(--ink-faint)' }}>
              המדריכים הפרקטיים — לבנות פעולה ומערך, לגייס חניכים, לקיים שיחות אישיות ולעצב בקנבה
            </p>
          </div>
        </div>
      </Reveal>

      <Reveal delay={40}>
        <div style={{ display: 'flex', flexWrap: 'wrap', gap: 8, marginBottom: 30 }}>
          {GUIDES.filter((g, i) => !g.variant || GUIDES.findIndex((x) => x.variant?.group === g.variant?.group) === i).map((g, i) => {
            const on = g.id === active || (!!g.variant && g.variant.group === guide.variant?.group);
            const col = pal(i);
            return (
              <button
                key={g.id}
                className={`chip${on ? ' is-active' : ''}`}
                style={{ background: on ? col.c : col.t, color: on ? '#ffffff' : col.c, borderColor: col.c }}
                onClick={() => openGuide(g.id)}
              >
                {g.tab}
              </button>
            );
          })}
        </div>
      </Reveal>

      <div key={guide.id} ref={contentRef} style={{ scrollMarginTop: 84 }}>
        {guide.variant && (
          <div className="variant-switch" role="tablist" aria-label="סוג הצמד" style={{ marginBottom: 18 }}>
            {GUIDES.filter((g) => g.variant?.group === guide.variant?.group).map((g) => (
              <button
                key={g.id}
                role="tab"
                aria-selected={g.id === guide.id}
                className={`variant-opt${g.id === guide.id ? ' is-on' : ''}`}
                onClick={() => setActive(g.id)}
              >
                <b>{g.variant!.label}</b>
                <span>{g.variant!.blurb}</span>
              </button>
            ))}
          </div>
        )}
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 12, marginBottom: 12 }}>
          <h2 style={{ fontSize: 22, fontWeight: 800 }}>{guide.heading}</h2>
          <CopyButton variant="mini" text={guideToText(guide)} label="העתקת המדריך" />
        </div>
        {guide.extra === 'seven-parts' && (
          <>
            <SevenParts />
            <h2 style={{ fontSize: 20, fontWeight: 800, margin: '0 0 6px' }}>עוד על בניית פעולה</h2>
            <p style={{ fontSize: 13.5, color: 'var(--ink-faint)', margin: '0 0 22px' }}>טיפים, טעויות נפוצות ורשימת בדיקה נוספת, שמשלימים את שיטת שבעת החלקים.</p>
          </>
        )}
        <GuideBody guide={guide} />
        {guide.extra === 'talk-cards' && <TalkCardsExtra />}
        {guide.extra === 'canva-links' && <CanvaExtra />}
      </div>

      <Reveal delay={80}>
        <div style={{ background: 'var(--flame-tint)', borderRadius: 18, padding: '26px 30px' }}>
          <h2 style={{ fontSize: 18, fontWeight: 800, marginBottom: 10 }}>לא בטוחים מאיפה להתחיל?</h2>
          <p style={{ fontSize: 14, color: 'var(--ink-soft)', marginBottom: 18 }}>
            אפשר לעיין בפעולות מוכנות ולראות איך השלד נראה בפועל, לשלוף מתודה מוכנה, או לבקש מ־ניצוץ
            עזרה בבנייה של פעולה או מערך לפי נושא וגיל.
          </p>
          <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap' }}>
            <Link to="/category/activities" className="btn btn-outline">פעולות מוכנות</Link>
            <Link to="/category/methods" className="btn btn-outline">מתודות</Link>
            <Link to="/ai" className="btn btn-flame">בנייה עם ניצוץ</Link>
          </div>
        </div>
      </Reveal>
    </div>
  );
}
