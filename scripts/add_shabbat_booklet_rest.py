def make(a):
    """a['steps'] = [(תווית, דקות, גוף או None, רשימת פריטים או None)]"""
    flow = []
    total = 0
    for label, minutes, body, items in a['steps']:
        step = {'label': f'{label} ({minutes} דק׳)'}
        if body:
            step['body'] = body
        if items:
            step['items'] = items
        flow.append(step)
        total += minutes
    act = dict(
        id=a['id'], title=a['title'], categorySlug='activities', subtopics=a['subtopics'],
        ageLabel=age_label(a['ageMin'], a['ageMax']), ageMin=a['ageMin'], ageMax=a['ageMax'],
        duration=total, groupSize='8–25 חניכים', equipment=a['equipment'], shabbat='שניהם', place='פנים',
        energy=a['energy'], depth=a['depth'], values=a['values'], tags=a['tags'], rating=a.get('rating', 4.5),
        character=a['character'], description=a['description'], goals=a['goals'],
        opening=a['steps'][0][2], method=a['method'], discussion=a['discussion'], flow=flow,
        sourceLink=a['sourceLink'], guideNotes=a['guide'] + LAST_LINE, summary=a['summary'], tip=a['tip'],
        shabbatNote=a['shabbatNote'], appendices=a['appendices'])
    if a.get('game'):
        act['game'] = a['game']
    return act


