def patch_personality():
    """מוסיף נספחים לפעולה הקיימת, פעם אחת בלבד (לפי שם הנספח)."""
    pid = 'kama-series-building-personality'
    acts = load('activities')
    target = next((a for a in acts if a['id'] == pid), None)
    if not target:
        print(f'{pid} not found: run add_kama_talpi.py first, then rerun this script')
        return 0
    apps = target.setdefault('appendices', [])
    have = {x['label'] for x in apps}
    added = 0
    for label, content in ((TRAITS_LABEL, TRAITS), (EXTRA_LABEL, EXTRA)):
        if label not in have:
            apps.append({'label': label, 'content': content})
            added += 1
    if added:
        save('activities', acts)
    return added


def publish():
    existing = {a['id'] for a in load('activities')}
    fresh = [a for a in (OPEN, SHALIACH) if a['id'] not in existing]
    print('activities added:', add_activities(fresh) if fresh else 0)
    print('appendices added to kama-series-building-personality:', patch_personality())


if __name__ == '__main__':
    publish()
