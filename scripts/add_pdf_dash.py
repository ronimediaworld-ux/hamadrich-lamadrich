AGE_LABEL = 'חניכי הנהגה, לקראת הדרכה'
AGE_MIN, AGE_MAX = 10, 12  # הקובץ לא מציין כיתה; אותו טווח כמו פעולות הנהגה אחרות לבוגרים


def minutes(label):
    m = re.search(r'\((\d+)\s*דק', label)
    return int(m.group(1)) if m else 0


def step(label, body=None, items=None, link=None, note=None):
    s = {'label': label}
    if body:
        s['body'] = body
    if items:
        s['items'] = items
    if link:
        s['link'] = link
    if note:
        s['note'] = note
    return s


def build(id, title, subtopics, values, tags, character, depth, energy, equipment, description, goals, flow,
          guide_notes, tip, appendices):
    """flow: רשימת step(); opening = הצעד הראשון, game = הצעד הראשון ששמו מתחיל ב״משחק״,
    method = שאר ההסברים והקטעים, discussion = כל הפריטים של שלבי ״דיון״, summary = הצעד האחרון."""
    def text(s):
        return s.get('body') or '\n'.join(s.get('items', []))

    games = [s for s in flow if s['label'].startswith('משחק')]
    discussions = [q for s in flow if s['label'].startswith('דיון') for q in s.get('items', [])]
    method_steps = [s for s in flow[1:-1] if not s['label'].startswith(('משחק', 'דיון'))]
    a = dict(
        id=id, title=title, categorySlug='activities', subtopics=subtopics,
        ageLabel=AGE_LABEL, ageMin=AGE_MIN, ageMax=AGE_MAX,
        duration=sum(minutes(s['label']) for s in flow), groupSize='10–25 משתתפים', equipment=equipment,
        shabbat='שניהם', place='פנים', energy=energy, depth=depth, values=values, tags=tags, rating=4.6,
        character=character, description=description, goals=goals, opening=text(flow[0]),
        method='\n\n'.join(text(s) for s in method_steps), discussion=discussions,
        guideNotes=guide_notes + '\n\nזמני השלבים הם הערכה שלנו (בקובץ המקור אין זמנים), ואפשר להתאים אותם לקבוצה.',
        summary=text(flow[-1]), tip=tip, flow=flow, appendices=appendices,
    )
    if games:
        a['game'] = '\n\n'.join(g['label'].split('(')[0].strip() + ': ' + text(g) for g in games)
    return a


