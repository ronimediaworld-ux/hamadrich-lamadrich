def minutes(label):
    m = re.search(r'\((\d+)\s*דק', label)
    return int(m.group(1)) if m else 0


def step(label, body=None, items=None, link=None, note=None):
    s = {'label': label}
    if body:
        s['body'] = body
    if items:
        s['items'] = items
    if link:
        s['link'] = link
    if note:
        s['note'] = note
    return s


def text(s):
    parts = []
    if s.get('body'):
        parts.append(s['body'])
    if s.get('items'):
        parts.append('\n'.join(s['items']))
    return '\n\n'.join(parts)


def build(id, title, lo, hi, group, subtopics, values, tags, character, depth, energy, place, equipment,
          description, goals, flow, game_labels, guide_notes, tip, appendices=None, reading=None, source_link=None):
    """opening = השלב הראשון, game = השלבים שבהם התווית מתחילה באחד מ-game_labels,
    method = כל שאר שלבי התוכן, discussion = פריטי שלב ״דיון״, summary = השלב האחרון."""
    games = [s for s in flow if s['label'].startswith(tuple(game_labels))] if game_labels else []
    discussion = [q for s in flow if s['label'].startswith('דיון') for q in s.get('items', [])]
    method_steps = [s for s in flow[1:-1] if s not in games and not s['label'].startswith('דיון')]
    a = dict(
        id=id, title=title, categorySlug='activities', subtopics=subtopics,
        ageLabel=age_label(lo, hi), ageMin=lo, ageMax=hi,
        duration=sum(minutes(s['label']) for s in flow), groupSize=group, equipment=equipment,
        shabbat='חול', place=place, energy=energy, depth=depth, values=values, tags=tags, rating=4.6,
        character=character, description=description, goals=goals, opening=text(flow[0]),
        method='\n\n'.join(text(s) for s in method_steps), discussion=discussion,
        guideNotes=guide_notes, summary=text(flow[-1]), tip=tip, flow=flow,
    )
    if games:
        a['game'] = '\n\n'.join(text(g) for g in games)
    if reading:
        a['reading'] = reading
    if source_link:
        a['sourceLink'] = source_link
    if appendices:
        a['appendices'] = appendices
    return a


