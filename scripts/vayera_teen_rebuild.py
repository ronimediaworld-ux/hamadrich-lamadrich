def verse(chapter, n):
    url = f'https://www.sefaria.org/api/texts/Genesis.{chapter}.{n}?context=0&commentary=0&vhe=Miqra_according_to_the_Masorah'
    d = json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40))
    h = d['he']
    t = re.sub('<[^>]+>', '', h if isinstance(h, str) else ' '.join(h)).replace('&thinsp;', ' ').replace('&nbsp;', ' ')
    t = t.replace('׃', '.')
    t = re.sub('[\u0591-\u05af\u05bd\u05c0]', '', t)
    return re.sub(r'\s+', ' ', t).replace('{פ}', '').strip()


