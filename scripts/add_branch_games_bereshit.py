def flat(x):
    if isinstance(x, str):
        return [x]
    o = []
    for y in x or []:
        o += flat(y)
    return o


def verses(ref):
    url = f'https://www.sefaria.org/api/texts/{ref}?context=0&commentary=0&vhe=Miqra_according_to_the_Masorah'
    d = json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40))
    t = re.sub('<[^>]+>', '', ' '.join(flat(d['he']))).replace('&thinsp;', ' ').replace('&nbsp;', ' ')
    t = re.sub('[֑-ֽ֯׀]', '', t)
    t = re.sub('י[ְ-ּ]*ה[ְ-ּ]*ו[ְ-ּ]*ה[ְ-ּ]*', 'ה׳', t)
    return re.sub(r'\s+', ' ', t).strip()


