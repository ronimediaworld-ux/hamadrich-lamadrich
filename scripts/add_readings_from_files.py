def validate(reading):
    assert reading['domain'] in DOMAINS, reading['id']
    assert 1 <= reading['ageMin'] <= reading['ageMax'] <= 12, reading['id']
    for k in ('id', 'title', 'domain', 'ageLabel', 'description', 'text', 'howToUse', 'source', 'tags'):
        assert reading.get(k), f"{reading['id']}: missing {k}"
    blob = ' '.join(str(v) for v in reading.values())
    for bad in BANNED:
        assert bad not in blob, f"{reading['id']}: contains banned word {bad}"
    if 'sourceLink' in reading:
        assert reading['sourceLink']['url'].startswith('https://'), reading['id']


def main(dry_run=False):
    seen = set()
    for r in NEW:
        assert r['id'] not in seen, f"duplicate id inside script: {r['id']}"
        seen.add(r['id'])
        validate(r)
    readings = load('readings')
    existing = {r['id'] for r in readings}
    added = [r for r in NEW if r['id'] not in existing]
    skipped = [r['id'] for r in NEW if r['id'] in existing]
    if not dry_run and added:
        readings.extend(added)
        save('readings', readings)
    print(f"{'(dry run) ' if dry_run else ''}added {len(added)}, skipped {len(skipped)} existing: {skipped}; total {len(readings) + (0 if dry_run else 0)}")


if __name__ == '__main__':
    main(dry_run='--dry-run' in sys.argv)
