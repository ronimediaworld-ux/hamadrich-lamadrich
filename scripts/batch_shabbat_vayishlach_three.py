def arrange(a, discussion_min, explanation, method, summary_min):
    """Re-order the flow into Roni's template and keep the reading and the method as two separate steps:
    opening, game, discussion, reading (text only), explanation, method (the hands-on task), summary.
    explanation: (text, minutes); method: (name, text, minutes). Checks the minutes add up to the duration."""
    opening, game, reading, disc, summ = a['flow']
    assert game['label'].startswith('משחק') and reading['label'].startswith('קטע קריאה')
    disc['label'] = f'דיון ({discussion_min} דק׳)'
    summ['label'] = f'סיכום ({summary_min} דק׳)'
    a['flow'] = [opening, game, disc, reading,
                 {'label': f'הסבר ({explanation[1]} דק׳)', 'body': explanation[0]},
                 {'label': f'מתודה: {method[0]} ({method[2]} דק׳)', 'body': method[1]},
                 summ]
    a['method'] = method[1]
    total = sum(int(re.search(r'\((\d+) דק', st['label']).group(1)) for st in a['flow'])
    assert total == a['duration'], (a['id'], total, a['duration'])
    return a


