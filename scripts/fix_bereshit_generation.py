UA = {'User-Agent': 'Mozilla/5.0 hamadrich-research'}


def sefaria(ref, **q):
    qs = '&'.join(f'{k}={v}' for k, v in q.items())
    url = f'https://www.sefaria.org/api/texts/{ref}?context=0&commentary=0' + (('&' + qs) if qs else '')
    return json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40))


def flat(x):
    if isinstance(x, str):
        return [x]
    out = []
    for y in x or []:
        out += flat(y)
    return out


def clean(t):
    t = re.sub(r'<[^>]+>', '', t).replace('&thinsp;', ' ').replace('&nbsp;', ' ')
    t = re.sub('[֑-ֽ֯]', '', t)  # טעמי מקרא — משאירים ניקוד
    t = t.replace('\u05C0', '')  # פסק
    t = re.sub('י[\u05B0-\u05BC]*ה[\u05B0-\u05BC]*ו[\u05B0-\u05BC]*ה[\u05B0-\u05BC]*', 'ה׳', t) if 'יְה' in t else t
    return re.sub(r'\s+', ' ', t).strip()


