def minutes(label):
    m = re.search(r'\((\d+)', label)
    return int(m.group(1)) if m else 0


def act(id, title, lo, hi, group, equipment, shabbat, place, energy, depth, values, tags, character, desc, goals, steps, notes, tip, shabbat_note, subtopics):
    flow = [({'label': l, 'items': b} if isinstance(b, list) else {'label': l, 'body': b}) for l, b in steps]
    bodies = [b for _, b in steps]
    return dict(
        id=id, title=title, categorySlug='activities', subtopics=subtopics, ageLabel='', ageMin=lo, ageMax=hi,
        duration=sum(minutes(l) for l, _ in steps), groupSize=group, equipment=equipment, shabbat=shabbat, place=place,
        energy=energy, depth=depth, values=values, tags=tags, rating=4.6, character=character, description=desc, goals=goals,
        opening=bodies[0], game=bodies[1], method=bodies[2], discussion=bodies[4], guideNotes=notes, summary=bodies[6], tip=tip,
        shabbatNote=shabbat_note, flow=flow,
    )


