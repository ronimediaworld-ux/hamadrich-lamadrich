"""Adds public-domain classic readings (Mishnah Avot, Rambam, Tchernichovsky, Rav Kook) as readings + staff-study pieces.
Texts are verbatim from Sefaria / Hebrew Wikisource (source_texts.json holds the Sefaria texts)."""
import json, re
from content_tools import load, save, age_label

T = json.load(open('source_texts.json', encoding='utf8'))


def clean(s):
    s = re.sub(r'<[^>]+>', '', s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def he(k):
    h = T[k]['he']
    if isinstance(h, list):
        return '\n\n'.join(clean(x) for x in h if x.strip())
    return clean(h)


SEF = 'https://www.sefaria.org/'
READINGS, STAFF = [], []


def R(id, title, domain, ages, description, text, howToUse, source, link, tags):
    lo, hi = ages
    READINGS.append({'id': id, 'title': title, 'domain': domain, 'ageLabel': age_label(lo, hi), 'ageMin': lo, 'ageMax': hi,
                     'description': description, 'text': text, 'howToUse': howToUse, 'source': source,
                     'sourceLink': {'title': link[0], 'url': link[1]}, 'tags': tags})


def S(id, title, topic, duration, forWhom, description, goals, opening, content, discussion, takeaway, link):
    STAFF.append({'id': id, 'title': title, 'topic': topic, 'duration': duration, 'forWhom': forWhom, 'description': description,
                  'goals': goals, 'opening': opening, 'content': content, 'discussion': discussion, 'takeaway': takeaway,
                  'sourceLink': {'title': link[0], 'url': link[1]}})


