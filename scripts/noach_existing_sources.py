def set_story(a, app_label, story, read_label, read_body, expl_add, guide_fix):
    for f in a['flow']:
        if f['label'].startswith(('סיפור', 'משל')):
            mins = re.search(r'[(](\d+) דק', f['label']).group(1)
            f['label'] = f"{read_label} ({mins} דק׳)"
            f['body'] = read_body
        if f['label'].startswith('הסבר') and expl_add:
            f['body'] = f['body'] + ' ' + expl_add
    a['appendices'][0] = {'label': app_label, 'content': story}
    g = a['guideNotes']
    g = re.sub(r'הסיפור מקורי לאתר\.[^.]*\.', '', g)
    g = re.sub(r'המשל הוא בעיבוד חדש[^.]*\.[^.]*\.', '', g)
    a['guideNotes'] = (g.strip() + ' ' + guide_fix).strip()
    a['method'] = re.sub(r'הסיפור בנספח א׳', 'הסיפור בנספח א׳', a['method'])


