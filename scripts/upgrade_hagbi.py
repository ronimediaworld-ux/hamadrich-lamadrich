def flat(x):
    if isinstance(x, str):
        return [x]
    o = []
    for y in x or []:
        o += flat(y)
    return o


def clean(t):
    t = re.sub(r'<[^>]+>', '', t).replace('&thinsp;', ' ').replace('&nbsp;', ' ')
    t = re.sub('[֑-ֽ֯׀]', '', t)
    return re.sub(r'\s+', ' ', t).strip()


def he(ref, vhe=None):
    url = f'https://www.sefaria.org/api/texts/{ref}?context=0&commentary=0' + (f'&vhe={vhe}' if vhe else '')
    return clean(' '.join(flat(json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=40))['he'])))


