def retell(a, story_label, story, reading_label, reading_body, extra_guide):
    for f in a['flow']:
        if f['label'].startswith('קטע קריאה'):
            mins = re.search(r'[(](\d+) דק', f['label']).group(1)
            f['label'] = f"{reading_label} ({mins} דק׳)"
            f['body'] = reading_body
            f.pop('note', None)
    verses_app = a['appendices'][0]
    a['appendices'] = [{'label': story_label, 'content': story},
                       {'label': verses_app['label'].replace('נספח א׳', 'נספח ב׳').replace('פסוקים', 'פסוקים מהפרשה (לבחירה)'), 'content': verses_app['content']}]
    a['method'] = a['method'].replace('הפסוקים בנספח א׳', 'הסיפור בנספח א׳')
    a['guideNotes'] = a['guideNotes'] + ' ' + extra_guide


